public class LecturaVariables{
    public static void main(String[] args) {
        String nombre = "Ana";
        int edad = 19;

        System.out.println(nombre);
        System.out.println(edad);

        edad = 20;

        System.out.println(edad);
    }
}

// Las lineas que se mostrarán en la terminal son:
// Ana
// 19
// 20 