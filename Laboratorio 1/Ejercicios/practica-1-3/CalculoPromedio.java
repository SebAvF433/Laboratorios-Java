public class CalculoPromedio {
    public static void main(String[] args){
        double nota1 = 4.2;
        double nota2 = 5.0;
        double nota3 = 3.6;

        double promedio = (nota1 + nota2 + nota3) / 3;
        System.out.println("Promedio: " + promedio);
    }
}

/*Tanto las variables como el promedio deben estar declaradas como double, si buscamos
obtener un resultado con decimales*/